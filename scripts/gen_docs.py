"""Write the reference pages that restate the code, from the code, so they cannot drift from it.

* ``docs/reference/tools.md`` -- every agent tool: what it does, what its connector must do, its arguments;
* ``docs/reference/configuration.md`` -- every setting, from `sim_mirror.config.schema`;
* ``docs/reference/cli.md`` -- every command and flag, from the argument parser;
* ``docs/reference/protocol.md`` -- the screen protocol's close codes and constants, from ``protocol/v1``;
* ``docs/compatibility.md`` -- where SimMirror is expected to work and where it was checked, from
  ``compat/matrix.toml``.

    uv run python scripts/gen_docs.py            # write them (`make generate`)
    uv run python scripts/gen_docs.py --check    # exit 1 if one is stale, writing nothing
"""

